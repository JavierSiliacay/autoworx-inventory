-- ============================================================
-- Upsert from staging into live inventory table
-- ============================================================
DO $$
DECLARE
    r RECORD;
    v_branch_id UUID;
BEGIN
    -- Get a default branch ID ('Main Distribution' or the first available)
    SELECT id INTO v_branch_id FROM public.branches WHERE name = 'Main Distribution' LIMIT 1;
    IF v_branch_id IS NULL THEN
        SELECT id INTO v_branch_id FROM public.branches LIMIT 1;
    END IF;

    FOR r IN SELECT * FROM _inv_import LOOP
        -- Attempt to update existing records by sku
        UPDATE public.inventory
        SET 
            product_name  = r.product_name,
            -- Only update quantity if the spreadsheet has a meaningful positive value
            quantity      = CASE WHEN r.quantity > 0 THEN r.quantity ELSE public.inventory.quantity END,
            price         = COALESCE(r.price, public.inventory.price),
            dealers_price = COALESCE(r.dealers_price, public.inventory.dealers_price),
            updated_at    = timezone('utc'::text, now())
        WHERE sku = r.sku;

        -- If no matching SKU was found, insert a new record
        IF NOT FOUND THEN
            INSERT INTO public.inventory (sku, product_name, quantity, price, dealers_price, branch_id, updated_at)
            VALUES (
                r.sku, 
                r.product_name, 
                r.quantity, 
                COALESCE(r.price, 0), 
                r.dealers_price, 
                v_branch_id,
                timezone('utc'::text, now())
            );
        END IF;
    END LOOP;
END $$;

-- ============================================================
-- Summary report — run after migration to verify
-- ============================================================
SELECT
  COUNT(*)                                                   AS total_skus_in_sheet,
  COUNT(*) FILTER (WHERE i.price IS NOT NULL)                AS skus_with_apc_price,
  COUNT(*) FILTER (WHERE i.dealers_price IS NOT NULL)        AS skus_with_dealer_price,
  COUNT(*) FILTER (WHERE i.quantity < 0)                     AS negative_stock_items
FROM _inv_import i;
